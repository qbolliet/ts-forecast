"""Golden master of ``HighFrequencyImputer``: every frozen case, bit for bit.

Reruns each case of ``tests/support/golden/manifest.json`` (matrix of
:func:`tests.support.golden.scenarios.build_cases`) and compares everything it
records with the golden file: outputs of ``fit_transform``, ``transform`` on
posterior data and both ``inverse_transform``, provenance matrices, plan
diagnostic frames, public fitted attributes, exceptions and warnings (category
and message, in emission order). The matrix itself must still match the
manifest. The golden files are regenerated by hand with
``tests/support/golden/generate.py``; the comparison only runs in the
environment of their generation (same versions, same platform).
"""
# Modules de base
import pytest

# Golden master : matrice, exécution, comparaison stricte, fichiers figés
from tests.support.golden.compare import assert_same
from tests.support.golden.scenarios import build_cases, run_case
from tests.support.golden.store import (
    GOLDEN_DIR,
    MANIFEST_NAME,
    environment_mismatches,
    read_manifest,
    read_record,
)

# Lecture du manifest à la collecte : un cas paramétré par entrée
if (GOLDEN_DIR / MANIFEST_NAME).exists():
    _MANIFEST = read_manifest()
    _MISMATCHES = environment_mismatches(_MANIFEST['environment'])
else:
    _MANIFEST = {'cases': [], 'environment': {}}
    _MISMATCHES = ['golden master never generated']

# Comparaison au bit près : seulement dans l'environnement de génération
pytestmark = [
    pytest.mark.slow,
    pytest.mark.skipif(
        bool(_MISMATCHES),
        reason='golden master generated in another environment, regenerate it with '
               'tests/support/golden/generate.py: ' + '; '.join(_MISMATCHES),
    ),
]

# Cas de la matrice courante, indexés par identifiant
_CASES = {case.case_id: case for case in build_cases()}


class TestMatrix:
    """The matrix of the code is the matrix of the golden files."""

    def test_same_cases_in_the_same_order(self):
        """``build_cases()`` yields the manifest cases, in order, with the same parameters."""
        recorded = [
            (entry['id'], entry['dataset'], entry['with_target'], entry['estimator'], entry['params'])
            for entry in _MANIFEST['cases']
        ]
        current = [
            (case_id, case.dataset, case.with_target, case.estimator, case.imputer_params())
            for case_id, case in _CASES.items()
        ]
        assert current == recorded


class TestGoldenCases:
    """Each case reproduces its golden record exactly."""

    @pytest.mark.parametrize(
        'entry', _MANIFEST['cases'], ids=[entry['id'] for entry in _MANIFEST['cases']]
    )
    def test_case_matches_golden_record(self, entry):
        """Outputs, provenance, plan, fitted attributes and warnings are unchanged."""
        expected = read_record(GOLDEN_DIR / entry['file'])
        actual = run_case(_CASES[entry['id']])
        assert_same(expected, actual, entry['id'])
